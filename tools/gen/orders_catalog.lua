--- Generate Orders catalog from src/vendor/assets/source/wc3_order_strings.csv
--- Usage: via tools/bake.lua

local path = dofile("tools/_path.lua")
path.setup()

local writeCatalogLib = dofile("tools/gen/write_catalog.lua")

local CSV_PATH = "src/vendor/assets/source/wc3_order_strings.csv"
local OUT_DIR = "src/data/generated"
local ORDER_COLUMN = 5

local function stripBom(s)
    if s:sub(1, 3) == "\239\187\191" then
        return s:sub(4)
    end
    return s
end

---@return string[][]
local function parseCsv(content)
    content = stripBom(content)
    local rows = {}
    local row = {}
    local field = {}
    local inQuotes = false
    local i = 1

    local function flushField()
        row[#row + 1] = table.concat(field)
        for j = 1, #field do
            field[j] = nil
        end
    end

    local function flushRow()
        if #row > 0 then
            rows[#rows + 1] = row
            row = {}
        end
    end

    while i <= #content do
        local c = content:sub(i, i)
        if inQuotes then
            if c == '"' then
                if content:sub(i + 1, i + 1) == '"' then
                    field[#field + 1] = '"'
                    i = i + 1
                else
                    inQuotes = false
                end
            else
                field[#field + 1] = c
            end
        elseif c == '"' then
            inQuotes = true
        elseif c == "," then
            flushField()
        elseif c == "\r" then
            -- skip
        elseif c == "\n" then
            flushField()
            flushRow()
        else
            field[#field + 1] = c
        end
        i = i + 1
    end

    if #field > 0 or #row > 0 then
        flushField()
        flushRow()
    end

    return rows
end

local function loadOrderStrings()
    local f, err = io.open(CSV_PATH, "rb")
    if not f then
        error("cannot read " .. CSV_PATH .. ": " .. tostring(err))
    end
    local content = f:read("*a")
    f:close()

    local rows = parseCsv(content)
    if #rows < 2 then
        error("CSV has no data rows: " .. CSV_PATH)
    end

    local entries = {}
    local seen = {}

    for r = 2, #rows do
        local cols = rows[r]
        local orderStr = cols[ORDER_COLUMN]
        if orderStr then
            orderStr = orderStr:match("^%s*(.-)%s*$")
            if orderStr ~= "" then
                if seen[orderStr] then
                    error(("duplicate order string in CSV: %q"):format(orderStr))
                end
                if not writeCatalogLib.isIdent(orderStr) then
                    error(("order string is not a Lua identifier: %q"):format(orderStr))
                end
                seen[orderStr] = true
                entries[orderStr] = orderStr
            end
        end
    end

    return entries
end

local function countKeys(t)
    local n = 0
    for _ in pairs(t) do
        n = n + 1
    end
    return n
end

local function generate()
    local entries = loadOrderStrings()
    writeCatalogLib.writeCatalog(OUT_DIR, "Orders", "Orders", entries, {
        banner = "--- Autogenerated by tools/gen/orders_catalog.lua — do not edit\n",
        aliasName = "OrderString",
    })
    print(("  Orders: %d"):format(countKeys(entries)))
end

generate()
