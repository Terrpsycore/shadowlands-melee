--- Build parent rawcode -> default cast order(s) from wc3_order_strings.csv
--- Usage: via tools/bake.lua

local path = dofile("tools/_path.lua")
path.setup()

local resolveLib = dofile("tools/gen/resolve_ability_order.lua")
local Orders = require("data.generated.Orders")

local CSV_PATH = "src/vendor/assets/source/wc3_order_strings.csv"
local OUT_PATH = "src/data/generated/vanilla_ability_orders.lua"
local ABIL_COLUMN = 4
local ORDER_COLUMN = 5

local function stripBom(s)
    if s:sub(1, 3) == "\239\187\191" then
        return s:sub(4)
    end
    return s
end

---@return string[][]
local function parseCsv(content)
    content = stripBom(content)
    local rows = {}
    local row = {}
    local field = {}
    local inQuotes = false
    local i = 1

    local function flushField()
        row[#row + 1] = table.concat(field)
        for j = 1, #field do
            field[j] = nil
        end
    end

    local function flushRow()
        if #row > 0 then
            rows[#rows + 1] = row
            row = {}
        end
    end

    while i <= #content do
        local c = content:sub(i, i)
        if inQuotes then
            if c == '"' then
                if content:sub(i + 1, i + 1) == '"' then
                    field[#field + 1] = '"'
                    i = i + 1
                else
                    inQuotes = false
                end
            else
                field[#field + 1] = c
            end
        elseif c == '"' then
            inQuotes = true
        elseif c == "," then
            flushField()
        elseif c == "\r" then
            -- skip
        elseif c == "\n" then
            flushField()
            flushRow()
        else
            field[#field + 1] = c
        end
        i = i + 1
    end

    if #field > 0 or #row > 0 then
        flushField()
        flushRow()
    end

    return rows
end

local function splitAbilCodes(raw)
    local codes = {}
    for token in raw:gmatch("[^,]+") do
        local code = token:match("^%s*(.-)%s*$")
        if code ~= "" then
            codes[#codes + 1] = code
        end
    end
    return codes
end

local function formatOrderValue(order)
    if type(order) == "string" then
        return string.format("%q", order)
    end
    return string.format("{ on = %q, off = %q }", order.on, order.off)
end

local function loadByParent()
    local f, err = io.open(CSV_PATH, "rb")
    if not f then
        error("cannot read " .. CSV_PATH .. ": " .. tostring(err))
    end
    local content = f:read("*a")
    f:close()

    local rows = parseCsv(content)
    if #rows < 2 then
        error("CSV has no data rows: " .. CSV_PATH)
    end

    ---@type table<string, string[]>
    local lists = {}

    local writeCatalogLib = dofile("tools/gen/write_catalog.lua")

    for r = 2, #rows do
        local cols = rows[r]
        local abilRaw = cols[ABIL_COLUMN]
        local orderStr = cols[ORDER_COLUMN]
        if abilRaw then
            abilRaw = abilRaw:match("^%s*(.-)%s*$")
            orderStr = orderStr and orderStr:match("^%s*(.-)%s*$") or ""
            if orderStr == "" then
                local desc = cols[3] and cols[3]:match("^%s*(.-)%s*$") or ""
                if writeCatalogLib.isIdent(desc) and Orders[desc] then
                    orderStr = desc
                end
            end
            if abilRaw ~= "" and orderStr ~= "" then
                for _, code in ipairs(splitAbilCodes(abilRaw)) do
                    local list = lists[code]
                    if not list then
                        list = {}
                        lists[code] = list
                    end
                    list[#list + 1] = orderStr
                end
            end
        end
    end

    local collapsed = {}
    for code, list in pairs(lists) do
        collapsed[code] = resolveLib.collapseOrderList(list)
    end
    return collapsed
end

local function writeCatalog(byParent)
    local keys = {}
    for k in pairs(byParent) do
        if byParent[k] ~= nil then
            keys[#keys + 1] = k
        end
    end
    table.sort(keys)

    local out = assert(io.open(OUT_PATH, "w"))
    out:write("--- Autogenerated by tools/gen/vanilla_ability_orders.lua — do not edit\n")
    out:write("--- Parent ability rawcode (data.parent) -> default WC3 cast order string(s).\n")
    out:write("return {\n")
    for _, code in ipairs(keys) do
        local order = byParent[code]
        local key = code:match("^[%a_][%w_]*$") and code or ("[" .. string.format("%q", code) .. "]")
        out:write("    " .. key .. " = " .. formatOrderValue(order) .. ",\n")
    end
    out:write("}\n")
    out:close()
end

local function countKeys(t)
    local n = 0
    for _ in pairs(t) do
        n = n + 1
    end
    return n
end

local function applyOverrides(byParent)
    local overrides = dofile("tools/gen/vanilla_ability_order_overrides.lua")
    for parent, order in pairs(overrides) do
        if byParent[parent] == nil then
            byParent[parent] = order
        end
    end
end

local function generate()
    local byParent = loadByParent()
    applyOverrides(byParent)
    writeCatalog(byParent)
    print(("  vanilla_ability_orders: %d parents"):format(countKeys(byParent)))
end

generate()
