local resolveLib = dofile("tools/gen/resolve_ability_order.lua")
local abilityExcludes = dofile("tools/gen/config/ability_excludes.lua")

local outPath = "src/data/generated/ability_meta.lua"
local orderExcludes = abilityExcludes.orderExcludes or {}

---@param order string|{ on: string, off: string }
---@return string
local function formatOrder(order)
    if type(order) == "string" then
        return string.format("%q", order)
    end
    return string.format("{ on = %q, off = %q }", order.on, order.off)
end

return function(assigned, db)
    local vanillaByParent = require("data.generated.vanilla_ability_orders")
    local rows = {}
    for slug, data in pairs(db) do
        local id = assigned[slug]
        if not id then
            error("missing generated id for ability " .. slug)
        end
        local order, excluded = resolveLib.resolve(data, slug, vanillaByParent, orderExcludes)
        rows[#rows + 1] = {
            id = id,
            slug = slug,
            order = order,
            orderExcluded = excluded,
        }
    end
    table.sort(rows, function(a, b)
        return a.id < b.id
    end)

    local f = assert(io.open(outPath, "w"))
    f:write("--- Autogenerated by tools/gen/ability_meta.lua — do not edit\n")
    f:write("return {\n")
    for _, row in ipairs(rows) do
        if row.orderExcluded then
            f:write(("    %s = { slug = %q, orderExcluded = true },\n"):format(row.id, row.slug))
        else
            f:write(
                ("    %s = { slug = %q, order = %s },\n"):format(row.id, row.slug, formatOrder(row.order))
            )
        end
    end
    f:write("}\n")
    f:close()
end
