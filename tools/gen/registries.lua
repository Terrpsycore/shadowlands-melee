--- Usage: lua tools/gen/registries.lua (or via tools/bake.lua)

local factionOrder = dofile("tools/gen/config/faction_order.lua")

local function ensureDir(path)
    local winPath = path:gsub("/", "\\")
    os.execute('if not exist "' .. winPath .. '" mkdir "' .. winPath .. '"')
end

local function listLuaBasenames(dir, excludes)
    local basenames = {}
    local winDir = dir:gsub("/", "\\")
    local handle = io.popen('dir /b "' .. winDir .. '\\*.lua" 2>nul')
    if not handle then
        return basenames
    end

    for line in handle:lines() do
        local name = line:match("^(%w+)%.lua$")
        if name and not excludes[name] then
            basenames[#basenames + 1] = name
        end
    end
    handle:close()

    table.sort(basenames)
    return basenames
end

local function addModules(registry, prefix, basenames)
    for _, name in ipairs(basenames) do
        registry[#registry + 1] = prefix .. name
    end
end

local function writeRegistry(outPath, registry)
    local outDir = outPath:match("^(.*)/[^/]+$")
    if outDir then
        ensureDir(outDir)
    end

    local out = assert(io.open(outPath, "w"))
    out:write("--- Autogenerated by tools/gen/registries.lua — do not edit\n")
    out:write("return {\n")
    for _, mod in ipairs(registry) do
        out:write('    "' .. mod .. '",\n')
    end
    out:write("}\n")
    out:close()

    print(("Generated %s (%d modules)"):format(outPath, #registry))
end

local function buildRegistry(profile)
    local registry = {}

    for _, source in ipairs(profile.sources) do
        addModules(registry, source.prefix, listLuaBasenames(source.dir, profile.excludes))
    end

    if profile.factionSources then
        for _, faction in ipairs(factionOrder) do
            for _, source in ipairs(profile.factionSources) do
                local dir = source.dirPattern:gsub("{faction}", faction)
                local prefix = source.prefixPattern:gsub("{faction}", faction)
                addModules(registry, prefix, listLuaBasenames(dir, profile.excludes))
            end
        end
    end

    return registry
end

