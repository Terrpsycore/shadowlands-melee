--- Usage: lua tools/gen/wscode_tab_index.lua (or via tools/bake.lua)
--- Maps embedded preload paths to WSCode tab names for error jump (A1).

local root = dofile("tools/_path.lua").setup()

local outPath = root .. "/src/scenario/generated/wscode_tab_index.lua"
local scanRoot = root .. "/src/scenario"

local function ensureDir(path)
    local winPath = path:gsub("/", "\\")
    os.execute('if not exist "' .. winPath .. '" mkdir "' .. winPath .. '"')
end

local function readBeginFileTab(firstLine)
    if not firstLine then
        return nil
    end
    return firstLine:match("^---@beginFile%s+(%S+)")
end

local function listLuaFiles(dir, acc, relPrefix)
    relPrefix = relPrefix or ""
    local winDir = dir:gsub("/", "\\")
    local handle = io.popen('dir /b /s "' .. winDir .. '\\*.lua" 2>nul')
    if not handle then
        return acc
    end
    for line in handle:lines() do
        local absPath = line:gsub("\\", "/")
        local rel = absPath:match("/src/(.+)$")
        if rel then
            acc[#acc + 1] = rel
        end
    end
    handle:close()
    table.sort(acc)
    return acc
end

local paths = listLuaFiles(scanRoot, {})

local byPath = {}
local tabToPath = {}
local duplicates = {}

for _, rel in ipairs(paths) do
    local preloadKey = rel:gsub("\\", "/")
    local filePath = root:gsub("\\", "/") .. "/src/" .. rel
    local f = assert(io.open(filePath, "r"))
    local firstLine = f:read("*l")
    f:close()

    local beginTab = readBeginFileTab(firstLine)
    local tab = beginTab or preloadKey:gsub("%.lua$", ""):gsub("^scenario/", "")

    if tabToPath[tab] and tabToPath[tab] ~= preloadKey then
        duplicates[#duplicates + 1] = string.format(
            'duplicate tab %q:\n  %s\n  %s',
            tab,
            tabToPath[tab],
            preloadKey
        )
    else
        tabToPath[tab] = preloadKey
    end

    byPath[preloadKey] = { tab = tab, preloadKey = preloadKey }
    local noAt = preloadKey:gsub("^@", "")
    byPath[noAt] = byPath[preloadKey]
    byPath["@" .. noAt] = byPath[preloadKey]
end

if #duplicates > 0 then
    error("wscode_tab_index: resolve tab name collisions (use unique ---@beginFile):\n" .. table.concat(duplicates, "\n"))
end

ensureDir(root .. "/src/scenario/generated")
local out = assert(io.open(outPath, "w"))
out:write("--- Autogenerated by tools/gen/wscode_tab_index.lua — do not edit\n")
out:write("return {\n")
out:write("    byPath = {\n")
for _, rel in ipairs(paths) do
    local preloadKey = rel:gsub("\\", "/")
    local entry = byPath[preloadKey]
    out:write(string.format('        [%q] = { tab = %q, preloadKey = %q },\n', preloadKey, entry.tab, entry.preloadKey))
end
out:write("    },\n")
out:write("}\n")
out:close()

print(("Generated %s (%d scenario modules)"):format(outPath, #paths))
