--- Copy referenced custom icons into imports/ for wc3 build.
--- Usage: lua tools/bake_imports.lua
---        wc3 build . --imports / wc3 go . --imports
---        wc3 assets . (via tools/bake_assets.lua)

local root = dofile("tools/_path.lua").setup()
local customPaths = dofile("tools/gen/custom_paths.lua")

local CUSTOM_ROOT = customPaths.resolveCustomRoot(root)
local IMPORTS_ROOT = root .. "/imports"
local MANIFEST_PATH = root .. "/.build/custom_imports.lua"

local DATA_DIR = root .. "/src/data"

local function normalizeSlashes(path)
    return path:gsub("/", "\\")
end

local function ensureDir(path)
    path = path:gsub("/", "\\")
    os.execute('if not exist "' .. path .. '" mkdir "' .. path .. '"')
end

local function readFile(path)
    local f, err = io.open(path, "r")
    if not f then
        return nil, err
    end
    local src = f:read("*a")
    f:close()
    return src
end

local function copyFile(src, dst)
    local inF, inErr = io.open(src, "rb")
    if not inF then
        return false, inErr
    end
    local data = inF:read("*a")
    inF:close()

    ensureDir(dst:match("^(.*)\\[^\\]+$") or dst)
    local outF, outErr = io.open(dst, "wb")
    if not outF then
        return false, outErr
    end
    outF:write(data)
    outF:close()
    return true
end

local function deleteFile(path)
    os.remove(path)
end

local function loadCustomIndex()
    package.loaded["vendor.assets.generated.custom_icon_index"] = nil
    local ok, index = pcall(require, "vendor.assets.generated.custom_icon_index")
    if not ok or type(index) ~= "table" then
        return {}
    end
    return index
end

local function collectIconKeysFromSource(src)
    local keys = {}
    for key in src:gmatch("Icons%.([_%w]+)") do
        keys[key] = true
    end
    return keys
end

local function walkDataLuaFiles(dir, out)
    dir = dir:gsub("/", "\\")
    local cmd = ('dir /s /b "%s\\*.lua"'):format(dir)
    local p = io.popen(cmd)
    if not p then
        return
    end
    for path in p:lines() do
        out[#out + 1] = path
    end
    p:close()
end

local function collectReferencedCustomKeys(index)
    local files = {}
    walkDataLuaFiles(DATA_DIR, files)

    local referenced = {}
    for _, path in ipairs(files) do
        local src = readFile(path)
        if src then
            for key in pairs(collectIconKeysFromSource(src)) do
                if index[key] then
                    referenced[key] = index[key]
                end
            end
        end
    end
    return referenced
end

local function readManifest()
    local f = io.open(MANIFEST_PATH, "r")
    if not f then
        return {}
    end
    f:close()

    local ok, listed = pcall(dofile, MANIFEST_PATH)
    if not ok or type(listed) ~= "table" then
        return {}
    end

    local paths = {}
    for _, path in ipairs(listed) do
        if type(path) == "string" and path ~= "" then
            paths[normalizeSlashes(path)] = true
        end
    end
    return paths
end

local function writeManifest(paths)
    ensureDir(root .. "/.build")
    local out = assert(io.open(MANIFEST_PATH, "w"))
    out:write("--- Autogenerated by tools/gen/sync_imports.lua — do not edit\n\n")
    out:write("return {\n")

    local keys = {}
    for path in pairs(paths) do
        keys[#keys + 1] = path
    end
    table.sort(keys)

    for i, path in ipairs(keys) do
        out:write(("    %q%s\n"):format(path, i < #keys and "," or ""))
    end
    out:write("}\n")
    out:close()
end

local function sync()
    local index = loadCustomIndex()
    if not next(index) then
        local old = readManifest()
        for path in pairs(old) do
            deleteFile(IMPORTS_ROOT .. "\\" .. path:gsub("/", "\\"))
        end
        writeManifest({})
        print("sync_imports: no custom icons")
        return
    end

    local referenced = collectReferencedCustomKeys(index)
    local importPaths = {}
    local copied = 0

    local function importAsset(entry, label)
        local src = CUSTOM_ROOT .. "/" .. entry.file:gsub("\\", "/")
        src = src:gsub("/", "\\")
        local dst = IMPORTS_ROOT .. "\\" .. normalizeSlashes(entry.path)
        importPaths[normalizeSlashes(entry.path)] = true

        local inF = io.open(src, "rb")
        if not inF then
            error(("sync_imports: missing custom asset for %s: %s"):format(label, src))
        end
        inF:close()

        local ok, err = copyFile(src, dst)
        if not ok then
            error(("sync_imports: failed to copy %s: %s"):format(label, tostring(err)))
        end
        copied = copied + 1
    end

    for key, entry in pairs(referenced) do
        importAsset(entry, ("Icons.%s"):format(key))
        if type(entry.companions) == "table" then
            for _, companion in ipairs(entry.companions) do
                importAsset(companion, ("Icons.%s (companion)"):format(key))
            end
        end
    end

    local previous = readManifest()
    for path in pairs(previous) do
        if not importPaths[path] then
            deleteFile(IMPORTS_ROOT .. "\\" .. path)
        end
    end

    writeManifest(importPaths)
    print(("sync_imports: %d custom icon(s) -> imports/"):format(copied))
end

sync()
