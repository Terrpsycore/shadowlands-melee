--- Shared catalog writers for asset and data codegen.

local M = {}

function M.escapeLuaString(s)
    if s:find("\n") or s:find("\\") then
        return "[[" .. s .. "]]"
    end
    return string.format("%q", s)
end

function M.isIdent(s)
    return type(s) == "string" and s:match("^[%a_][%w_]*$") ~= nil
end

function M.ensureDir(path)
    path = path:gsub("/", "\\")
    os.execute('if not exist "' .. path .. '" mkdir "' .. path .. '"')
end

---@param outDir string
---@param name string module/table name
---@param className string LuaLS class name
---@param entries table<string, string>
---@param opts? { banner?: string, aliasName?: string }
function M.writeCatalog(outDir, name, className, entries, opts)
    opts = opts or {}
    M.ensureDir(outDir)
    local out = assert(io.open(outDir .. "/" .. name .. ".lua", "w"))
    out:write(opts.banner or "--- Autogenerated — do not edit\n")
    out:write("---@class " .. className .. "\n")
    out:write("local " .. name .. " = {\n")

    local keys = {}
    for k in pairs(entries) do
        keys[#keys + 1] = k
    end
    table.sort(keys)

    for _, k in ipairs(keys) do
        local key = M.isIdent(k) and k or ("[" .. M.escapeLuaString(k) .. "]")
        out:write("    " .. key .. " = " .. M.escapeLuaString(entries[k]) .. ",\n")
    end

    out:write("}\n")

    if opts.aliasName then
        out:write("\n---@alias " .. opts.aliasName .. "\n")
        for _, k in ipairs(keys) do
            local literal = M.escapeLuaString(entries[k])
            out:write("---| " .. literal .. "\n")
        end
        out:write("\n")
    end

    out:write("\nreturn " .. name .. "\n")
    out:close()
end

return M
