local libDir = "src/lib/objediting"
local metaPath = libDir .. "/.meta.lua"

local function readFile(path)
    local file = assert(io.open(path, "r"))
    local text = file:read("*a")
    file:close()
    return text
end

local function listLuaFiles(dir)
    local files = {}
    local handle = io.popen('dir /b "' .. dir:gsub("/", "\\") .. '" 2>nul')
    if not handle then
        return files
    end
    for name in handle:lines() do
        if name:match("%.lua$") and name ~= "init.lua" then
            files[#files + 1] = dir .. "/" .. name
        end
    end
    handle:close()
    table.sort(files)
    return files
end

local function parseClass(text)
    local className, superName = text:match("---@class ([%w_]+): ([%w_]+)")
    if not className then
        return nil
    end
    local hasSingleArgCtor = text:match(
        "function " .. className .. ":constructor%(id%)"
    ) ~= nil
    return {
        className = className,
        superName = superName,
        singleArgCtor = hasSingleArgCtor,
    }
end

local classes = {}

local inventory = parseClass(readFile(libDir .. "/inventory.lua"))
if inventory then
    classes[#classes + 1] = inventory
end

for _, path in ipairs(listLuaFiles(libDir .. "/bases")) do
    local info = parseClass(readFile(path))
    if info then
        classes[#classes + 1] = info
    end
end

table.sort(classes, function(a, b)
    return a.className < b.className
end)

local out = assert(io.open(metaPath, "w"))
out:write("--- Autogenerated by tools/gen/objediting_meta.lua - do not edit\n")
out:write("---@meta\n\n")

for _, info in ipairs(classes) do
    out:write(("---@class %s: %s\n"):format(info.className, info.superName))
    out:write("---@field def ObjectDefinition\n\n")
    out:write("---@param id string|integer\n")
    if not info.singleArgCtor then
        out:write("---@param superId string|integer\n")
    end
    out:write(("---@return %s\n"):format(info.className))
    if info.singleArgCtor then
        out:write(("function %s:new(id) end\n\n"):format(info.className))
    else
        out:write(("function %s:new(id, superId) end\n\n"):format(info.className))
    end
end

out:close()
