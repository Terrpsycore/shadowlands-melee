--- Usage: lua objediting/gen_ability_registry.lua

local GENERATED_DIR = "src/scenario/generated"
local OUT_PATH = GENERATED_DIR .. "/abilities_registry.lua"

local factionOrder = dofile("objediting/ability_registry_order.lua")
local excludes = dofile("objediting/ability_registry_excludes.lua")

local function ensureDir(path)
    local winPath = path:gsub("/", "\\")
    os.execute('if not exist "' .. winPath .. '" mkdir "' .. winPath .. '"')
end

local function listLuaBasenames(dir)
    local basenames = {}
    local winDir = dir:gsub("/", "\\")
    local handle = io.popen('dir /b "' .. winDir .. '\\*.lua" 2>nul')
    if not handle then
        return basenames
    end

    for line in handle:lines() do
        local name = line:match("^(%w+)%.lua$")
        if name and not excludes[name] then
            basenames[#basenames + 1] = name
        end
    end
    handle:close()

    table.sort(basenames)
    return basenames
end

local function addModules(registry, prefix, basenames)
    for _, name in ipairs(basenames) do
        registry[#registry + 1] = prefix .. name
    end
end

local registry = {}

addModules(registry, "scenario.mechanics.", listLuaBasenames("src/scenario/mechanics"))

for _, faction in ipairs(factionOrder) do
    local dir = "src/scenario/factions/" .. faction .. "/abilities"
    addModules(registry, "scenario.factions." .. faction .. ".abilities.", listLuaBasenames(dir))
end

ensureDir(GENERATED_DIR)

local out = assert(io.open(OUT_PATH, "w"))
out:write("--- Autogenerated by objediting/gen_ability_registry.lua — do not edit\n")
out:write("return {\n")
for _, mod in ipairs(registry) do
    out:write('    "' .. mod .. '",\n')
end
out:write("}\n")
out:close()

print(("Generated %s (%d modules)"):format(OUT_PATH, #registry))
